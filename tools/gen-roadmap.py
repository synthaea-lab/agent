#!/usr/bin/env python3
"""Generate docs/roadmap.md from docs/capabilities.md and the tracking issues.

Reads every `partial` and `planned` row of docs/capabilities.md, groups the rows
by their tracking issue, fetches each issue's title, state and Priority field
from GitHub (through the `gh` CLI), and writes docs/roadmap.md grouped by
Priority.

Standard library only, plus an authenticated `gh` on PATH.

Usage: python3 tools/gen-roadmap.py [--repo owner/name] [repo-root]
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

PROJECT_BOARD = "https://github.com/orgs/synthaea-lab/projects/1"
ISSUE_RE = re.compile(r"\[#(\d+)\]\((https://github\.com/[\w.-]+/[\w.-]+/issues/\d+)\)")
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
# Parenthetical asides in issue titles that cite internal design-record numbers
# (three capitals, dash, four digits) mean nothing to a public reader.
ASIDE_RE = re.compile(r"\s*\([^)]*\b[A-Z]{3}-\d{4}\b[^)]*\)")

PRIORITIES = [
    ("Urgent", "Urgent: before the public beta"),
    ("High", "High: production-ready"),
    ("Medium", "Medium: later"),
    ("Low", "Low: later"),
    (None, "Not yet prioritized"),
]


def parse_capabilities(path: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    area = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("### "):
            area = line[4:].strip()
            continue
        if not line.startswith("| ") or line.startswith("| ---"):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
        if len(cells) != 5 or cells[1] not in ("partial", "planned"):
            continue
        issue = ISSUE_RE.search(cells[3])
        if not issue:
            raise SystemExit(f"capabilities.md: '{cells[0]}' has no tracking issue")
        doc = LINK_RE.search(cells[4])
        rows.append({
            "area": area,
            "capability": cells[0],
            "status": cells[1],
            "number": issue.group(1),
            "url": issue.group(2),
            "doc_label": doc.group(1) if doc else "",
            "doc": doc.group(2) if doc else "",
        })
    return rows


def fetch_issues(repo: str, numbers: list[str]) -> dict[str, dict]:
    owner, name = repo.split("/", 1)
    fields = (
        "number title state issueFieldValues(first:5){nodes{... on IssueFieldSingleSelectValue"
        "{name field{... on IssueFieldSingleSelect{name}}}}}"
    )
    body = "".join(f"i{n}:issue(number:{n}){{{fields}}}" for n in numbers)
    query = f'{{repository(owner:"{owner}",name:"{name}"){{{body}}}}}'
    out = subprocess.run(
        ["gh", "api", "graphql", "-f", f"query={query}"],
        capture_output=True, text=True, check=True,
    ).stdout
    result: dict[str, dict] = {}
    for issue in json.loads(out)["data"]["repository"].values():
        priority = None
        for node in issue["issueFieldValues"]["nodes"]:
            if node and (node.get("field") or {}).get("name") == "Priority":
                priority = node["name"]
        result[str(issue["number"])] = {
            "title": ASIDE_RE.sub("", issue["title"]).strip(),
            "state": issue["state"],
            "priority": priority,
        }
    return result


def render(rows: list[dict[str, str]], issues: dict[str, dict]) -> str:
    out = [
        "# Roadmap",
        "",
        "Generated by `tools/gen-roadmap.py` from the `partial` and `planned` rows of "
        "[capabilities.md](capabilities.md) and the Priority field of their tracking issues. "
        "Do not edit by hand: change the capability row or the issue, then regenerate.",
        "",
        f"Live status and ordering are on the [project board]({PROJECT_BOARD}).",
        "",
        "| Priority | Meaning |",
        "| --- | --- |",
        "| Urgent | Needed before the public beta. |",
        "| High | Needed for a production-ready agent. |",
        "| Medium, Low | Later. |",
        "| Not yet prioritized | Tracked, not triaged on the board yet. |",
        "",
    ]
    by_issue: dict[str, list[dict[str, str]]] = {}
    for row in rows:
        by_issue.setdefault(row["number"], []).append(row)
    known = {p for p, _ in PRIORITIES if p}
    for key, heading in PRIORITIES:
        numbers = sorted(
            (n for n in by_issue
             if (issues[n]["priority"] if issues[n]["priority"] in known else None) == key),
            key=int,
        )
        if not numbers:
            continue
        out += [f"## {heading}", ""]
        for n in numbers:
            info = issues[n]
            state = "" if info["state"] == "OPEN" else f" ({info['state'].lower()})"
            out.append(f"### [#{n}]({by_issue[n][0]['url']}) {info['title']}{state}")
            out.append("")
            for row in by_issue[n]:
                doc = f" See [{row['doc_label']}]({row['doc']})." if row["doc"] else ""
                out.append(f"- {row['capability']} ({row['status']}, {row['area']}).{doc}")
            out.append("")
    return "\n".join(out)


def main() -> int:
    args = sys.argv[1:]
    repo = "synthaea-lab/agent"
    if args[:1] == ["--repo"]:
        repo, args = args[1], args[2:]
    root = Path(args[0] if args else Path(__file__).resolve().parent.parent).resolve()
    rows = parse_capabilities(root / "docs" / "capabilities.md")
    numbers = sorted({r["number"] for r in rows}, key=int)
    issues = fetch_issues(repo, numbers)
    (root / "docs" / "roadmap.md").write_text(render(rows, issues), encoding="utf-8")
    print(f"gen-roadmap: {len(rows)} capabilities across {len(numbers)} issues")
    return 0


if __name__ == "__main__":
    sys.exit(main())
